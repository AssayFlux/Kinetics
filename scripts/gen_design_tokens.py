#!/usr/bin/env python3
"""Compile design/tokens.json to deterministic Kotlin and CSS token files."""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "tokens.json"
KOTLIN = ROOT / "android" / "designsystem" / "src" / "main" / "java" / "org" / "assayflux" / "designsystem" / "GeneratedTokens.kt"
CSS = ROOT / "web" / "viewers" / "src" / "styles" / "kinetics-tokens.css"

def main() -> int:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    shared = data["shared"]
    spacing = shared["spacing_dp"]
    radii = shared["radii_dp"]
    lines = [
        "// Generated by scripts/gen_design_tokens.py; do not edit.",
        "package org.assayflux.designsystem",
        "",
        "internal object GeneratedTokens {",
        "    val spacingDp = listOf(" + ", ".join(map(str, spacing)) + ")",
        "    val radiiDp = listOf(" + ", ".join(map(str, radii)) + ")",
        f"    const val minTouchTargetDp = {shared['touch_target_min_dp']}",
        f"    const val maxReadableContentDp = {shared['max_readable_content_dp']}",
        "}",
        "",
    ]
    KOTLIN.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN.write_text("\n".join(lines), encoding="utf-8")
    css = [":root {"]
    css += [f"  --kinetics-space-{i}: {value}px;" for i, value in enumerate(spacing)]
    css += [f"  --kinetics-radius-{i}: {value}px;" for i, value in enumerate(radii)]
    css += [f"  --kinetics-touch-target-min: {shared['touch_target_min_dp']}px;", "}"]
    CSS.parent.mkdir(parents=True, exist_ok=True)
    CSS.write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"Generated {KOTLIN.relative_to(ROOT)} and {CSS.relative_to(ROOT)}")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
