#!/usr/bin/env python3
"""Compile design/tokens.json into deterministic Compose and WebView tokens."""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "tokens.json"
KOTLIN = (
    ROOT / "android" / "designsystem" / "src" / "main" / "java"
    / "org" / "assayflux" / "designsystem" / "GeneratedTokens.kt"
)
CSS = ROOT / "web" / "viewers" / "src" / "styles" / "kinetics-tokens.css"
PROPERTIES = (
    "background", "surface", "surface_alt", "text", "muted",
    "primary", "secondary", "tertiary", "outline",
)


def identifier(value: str) -> str:
    words = re.sub(r"[^A-Za-z0-9]+", "_", value).strip("_").split("_")
    return "".join(word[:1].upper() + word[1:] for word in words)


def kotlin_property(value: str) -> str:
    words = value.split("_")
    return words[0] + "".join(word[:1].upper() + word[1:] for word in words[1:])


def kotlin_source(data: dict[str, Any]) -> str:
    shared = data["shared"]
    lines = [
        "// Generated by scripts/gen_design_tokens.py; do not edit.",
        "package org.assayflux.designsystem",
        "",
        "import androidx.compose.ui.graphics.Color",
        "",
        "data class KineticsPalette(",
    ]
    for index, prop in enumerate(PROPERTIES):
        suffix = "," if index < len(PROPERTIES) - 1 else ""
        lines.append(f"    val {kotlin_property(prop)}: Color{suffix}")
    lines += [")", "", "object KineticsTokens {"]
    lines.append(f"    val spacingDp = listOf({', '.join(map(str, shared['spacing_dp']))})")
    lines.append(f"    val radiiDp = listOf({', '.join(map(str, shared['radii_dp']))})")
    lines.append(f"    const val minTouchTargetDp = {shared['touch_target_min_dp']}")
    lines.append(f"    const val targetGapDp = {shared['target_gap_dp']}")
    lines.append(f"    const val maxReadableContentDp = {shared['max_readable_content_dp']}")
    for family in ("light", "dark", "neon"):
        for palette in data["theme_families"][family]["themes"]:
            lines.append(f"    val {identifier(palette['id'])} = KineticsPalette(")
            for index, prop in enumerate(PROPERTIES):
                color = palette[prop].removeprefix("#")
                suffix = "," if index < len(PROPERTIES) - 1 else ""
                lines.append(f"        {kotlin_property(prop)} = Color(0xFF{color}){suffix}")
            lines.append("    )")
    lines += ["}", ""]
    return "\n".join(lines)


def css_source(data: dict[str, Any]) -> str:
    shared = data["shared"]
    lines = ["/* Generated by scripts/gen_design_tokens.py; do not edit. */", ":root {"]
    lines += [f"  --kinetics-space-{i}: {value}px;" for i, value in enumerate(shared["spacing_dp"])]
    lines += [f"  --kinetics-radius-{i}: {value}px;" for i, value in enumerate(shared["radii_dp"])]
    lines += [
        f"  --kinetics-touch-target-min: {shared['touch_target_min_dp']}px;",
        f"  --kinetics-target-gap: {shared['target_gap_dp']}px;",
        f"  --kinetics-readable-width: {shared['max_readable_content_dp']}px;",
    ]
    for family in ("light", "dark", "neon"):
        for palette in data["theme_families"][family]["themes"]:
            for prop in PROPERTIES:
                palette_name = palette["id"].replace("_", "-")
                property_name = prop.replace("_", "-")
                css_name = f"--kinetics-{palette_name}-{property_name}"
                lines.append(f"  {css_name}: {palette[prop]};")
    lines += ["}", ""]
    return "\n".join(lines)


def main() -> int:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    kotlin = kotlin_source(data)
    css = css_source(data)
    KOTLIN.parent.mkdir(parents=True, exist_ok=True)
    CSS.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN.write_text(kotlin, encoding="utf-8")
    CSS.write_text(css, encoding="utf-8")
    print(f"Generated {KOTLIN.relative_to(ROOT)} and {CSS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
