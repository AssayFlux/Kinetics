#!/usr/bin/env python3
"""Generate the UI component catalogue from design tokens and the design-system contract."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOKENS = ROOT / "design" / "tokens.json"
OUTPUT = ROOT / "docs" / "ui" / "component-catalogue.md"
COMPONENTS = (
    ("Navigation", "Compact bottom bar; medium/expanded rail; large permanent drawer. "
     "Compact-height windows prioritize rail navigation."),
    ("Surfaces", "Material 3 cards, outlined cards, grouped settings surfaces and empty states."),
    ("Actions", "Primary and outlined buttons, import/export actions and filter chips."),
    (
        "Status",
        "Text-labelled job states and capability maturity labels; colour is never the only signal.",
    ),
    (
        "Research context",
        "Research Mode and local-first privacy context; full persistent global chips remain open.",
    ),
    (
        "Scientific data",
        "Sequence, structure, chart and provenance viewer components remain planned.",
    ),
)


def main() -> int:
    data = json.loads(TOKENS.read_text(encoding="utf-8"))
    lines = [
        "<!-- Generated by scripts/gen_component_catalogue.py; do not edit. -->",
        "# Kinetics component catalogue",
        "",
        "**Status:** source catalogue only; no screenshot, accessibility or device "
        "pass is implied.",
        "",
        "## Theme families",
        "",
    ]
    for family in ("light", "dark", "neon"):
        lines.extend([f"### {family.title()}", ""])
        for palette in data["theme_families"][family]["themes"]:
            lines.append(
                f"- **{palette['name']}** ({palette['id']}) — background "
                f"{palette['background']}, primary {palette['primary']}, "
                f"secondary {palette['secondary']}."
            )
        lines.append("")
    lines += ["## Component groups", ""]
    for name, description in COMPONENTS:
        lines.append(f"- **{name}:** {description}")
    lines += [
        "",
        "## Shared layout tokens",
        "",
        f"- Spacing: {', '.join(str(value) for value in data['shared']['spacing_dp'])} dp.",
        f"- Corner radii: {', '.join(str(value) for value in data['shared']['radii_dp'])} dp.",
        f"- Minimum touch target: {data['shared']['touch_target_min_dp']} dp.",
        f"- Target spacing: {data['shared']['target_gap_dp']} dp.",
        f"- Maximum readable content width: {data['shared']['max_readable_content_dp']} dp.",
        "",
        "## Proof status",
        "",
        "The development gallery composable lives in android/designsystem. It is not yet "
        "exposed through a debug-only route/activity. Compact/medium/expanded screenshots, "
        "light/dark/neon contrast checks, TalkBack, 200% text, RTL and foldable tests remain open.",
        "",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Generated {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
